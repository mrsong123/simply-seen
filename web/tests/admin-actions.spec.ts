  await page.getByLabel("总库存", { exact: true }).nth(1).fill("3");
  await page.getByRole("button", { name: "保存商品" }).click();
  await expect(page.getByRole("dialog")).not.toBeVisible();
  await find(page, product);
  await page.getByRole("button", { name: "编辑", exact: true }).click();
  await expect(page.getByLabel("SKU编码", { exact: true })).toHaveCount(2);
  await page.getByRole("button", { name: "移除规格2", exact: true }).click();
  await page.getByRole("button", { name: "撤销上次移除" }).click();
  await expect(page.getByLabel("SKU编码", { exact: true })).toHaveCount(2);
  await page.getByRole("button", { name: "移除规格2", exact: true }).click();
  await page.getByRole("button", { name: "保存商品" }).click();
  await expect(page.getByRole("dialog")).not.toBeVisible();
  await page.getByRole("button", { name: "编辑", exact: true }).click();
  await expect(page.getByLabel("SKU编码", { exact: true })).toHaveCount(1);
  await expect(page.getByRole("heading", { name: "历史停用规格" })).toBeVisible();
  await expect(page.getByRole("dialog").getByText("备用规格 · QA_B_" + tag)).toBeVisible();
  await page.getByRole("button", { name: "关闭弹窗" }).click();
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "导出当前页" }).click();
  expect((await download).suggestedFilename()).toContain("当前页");

  await page.goto("/admin/accounts");
  for (const [name, role] of [[username, "ADMIN"], [operator, "OPERATOR"], [finance, "FINANCE"]]) {
    await page.getByRole("button", { name: "新增账号" }).click();
    await page.getByRole("dialog").getByLabel("账号", { exact: true }).fill(name);
    await page.getByLabel("初始密码（至少12位）", { exact: true }).fill(password);
    await page.getByLabel("角色", { exact: true }).selectOption(role);
    await page.getByRole("button", { name: "创建账号", exact: true }).click();
    await expect(page.getByRole("dialog")).not.toBeVisible();
  }
  const operatorContext = await browser.newContext();
  const operatorPage = await operatorContext.newPage();
  await signIn(operatorPage, operator, password);
  await expect(operatorPage.getByRole("navigation").getByRole("link", { name: "商品管理" })).toBeVisible();
  await expect(operatorPage.getByRole("navigation").getByRole("link", { name: "账号与权限" })).toHaveCount(0);
  await operatorPage.goto("/admin/accounts");
  await expect(operatorPage).toHaveURL(/\/admin\/?$/);
  const operatorToken = await operatorPage.evaluate(() => JSON.parse(localStorage.getItem("sj-admin") || "null")?.token);
  const denied = await operatorPage.request.get("/api/v1/admin/records/accounts", { headers: { Authorization: "Bearer " + operatorToken } });
  expect(denied.status()).toBe(403);
  const reviewerContext = await browser.newContext();
  const reviewer = await reviewerContext.newPage();
  await signIn(reviewer, username, password);
  await page.goto("/admin/rules");
  await page.getByRole("button", { name: "新建规则草稿" }).click();
  const saved = page.waitForResponse(response => response.request().method() === "POST" && response.url().endsWith("/api/v1/admin/rules"));
  await page.getByRole("button", { name: "保存待复核草稿" }).click();
