import { test, expect, type Page } from "@playwright/test";
import { randomBytes } from "node:crypto";
import { readAdminCredentials } from "./support/admin-credentials";
const initial = readAdminCredentials();
async function signIn(page: Page, username: string, password: string) {
  await page.goto("/admin/login");
  await page.getByLabel("账号", { exact: true }).fill(username);
  await page.getByLabel("密码", { exact: true }).fill(password);
  await page.getByRole("button", { name: "安全登录" }).click();
  await expect(page.getByRole("heading", { name: "经营概览" })).toBeVisible();
}
async function search(page: Page, text: string) {
  const loaded = page.waitForResponse(response => {
    const url = new URL(response.url());
    return response.request().method() === "GET" && url.pathname.startsWith("/api/v1/admin/records/") && url.searchParams.get("search") === text;
  });
  await page.getByRole("textbox", { name: "搜索管理记录" }).fill(text);
  expect((await loaded).status()).toBe(200);
}
async function find(page: Page, text: string) {
  await search(page, text);
  await expect(page.getByRole("table").locator("tbody > tr")).toHaveCount(1);
  await expect(page.getByRole("table").getByText(text, { exact: true }).first()).toBeVisible();
}
