  const draft = page.getByRole("row").filter({ has: page.getByRole("button", { name: "审批", exact: true }) }).first();
  await expect(draft.getByRole("button", { name: "审批", exact: true })).toBeDisabled();
  const ruleId = (await draft.locator("td").first().innerText()).trim();
