  test.setTimeout(180000);
  const tag = Date.now().toString(36) + randomBytes(2).toString("hex");
  const category = "验收分类" + tag, product = "规格验收" + tag;
  const username = "qa_admin_" + tag, operator = "qa_op_" + tag, finance = "qa_fin_" + tag;
  const password = "QA-only-" + randomBytes(16).toString("hex");
  await signIn(page, initial.username, initial.password);
  await page.goto("/admin/products");
  await page.getByRole("button", { name: "管理分类" }).click();
  await page.getByLabel("新增分类", { exact: true }).fill(category);
  await page.getByRole("button", { name: "保存分类" }).click();
  await expect(page.getByRole("dialog").getByText(category, { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "关闭弹窗" }).click();
  await page.getByRole("button", { name: "新增商品" }).click();
  await page.getByLabel("商品名称", { exact: true }).fill(product);
  await page.getByLabel("商品分类", { exact: true }).selectOption({ label: category });
  await page.getByLabel("商品详情", { exact: true }).fill("通过实际管理界面创建、编辑及停用规格的验收商品。");
  await page.getByLabel("SKU编码", { exact: true }).fill("QA_A_" + tag);
  await page.getByLabel("总库存", { exact: true }).fill("8");
  await page.getByRole("button", { name: "增加规格" }).click();
  await page.getByLabel("规格名称", { exact: true }).nth(1).fill("备用规格");
